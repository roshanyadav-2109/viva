create function public.submit_item(p_kind text, p_payload jsonb) returns bigint
language plpgsql security definer set search_path = '' as $$
declare
  u uuid := auth.uid();
  v jsonb;
  v_subject text;
  v_level integer;
  v_proctor text;
  v_items jsonb;
  v_id bigint;
  v_date date;
begin
  if u is null then raise exception 'sign in required' using errcode = '28000'; end if;
  if p_payload is null or jsonb_typeof(p_payload) <> 'object' or length(p_payload::text) > 60000 then
    raise exception 'invalid submission' using errcode = '22023';
  end if;
  if (select count(*) from public.submissions where user_id = u and created_at > now() - interval '24 hours') >= 20
     or (select count(*) from public.submissions where user_id = u and status = 'pending') >= 30 then
    raise exception 'submission limit reached, try again tomorrow' using errcode = '54000';
  end if;

  if p_kind = 'proctor' then
    v_proctor := private.clean(p_payload->>'code', 40);
    if v_proctor !~ '^[A-Za-z0-9][A-Za-z0-9 ._-]{1,39}$' then
      raise exception 'invalid proctor name' using errcode = '22023';
    end if;
    v := jsonb_build_object('code', v_proctor);

  elsif p_kind in ('session', 'review') then
    v_subject := upper(private.clean(p_payload->>'subject', 20));
    v_level := case when (p_payload->>'level') ~ '^[1-3]$' then (p_payload->>'level')::int end;
    v_proctor := private.clean(p_payload->>'proctor', 40);
    if not exists (select 1 from public.subjects where code = v_subject) or v_level is null then
      raise exception 'invalid subject or level' using errcode = '22023';
    end if;
    if v_proctor !~ '^[A-Za-z0-9][A-Za-z0-9 ._-]{1,39}$' then
      raise exception 'invalid proctor' using errcode = '22023';
    end if;
    v_date := case when (p_payload->>'held_on') ~ '^\d{4}-\d{2}-\d{2}$' then (p_payload->>'held_on')::date end;
    v := jsonb_build_object('subject', v_subject, 'level', v_level, 'proctor', v_proctor, 'held_on', v_date);
    if p_kind = 'review' then
      if char_length(private.clean(p_payload->>'body', 3000)) < 10 then
        raise exception 'review is too short' using errcode = '22023';
      end if;
      v := v || jsonb_build_object('body', private.clean(p_payload->>'body', 3000));
    else
      if jsonb_typeof(p_payload->'questions') <> 'array' then
        raise exception 'add at least one question' using errcode = '22023';
      end if;
      select coalesce(jsonb_agg(t), '[]'::jsonb) into v_items from (
        select private.clean(e, 1000) as t
        from jsonb_array_elements_text(p_payload->'questions') e
        where jsonb_typeof(to_jsonb(e)) = 'string' and char_length(private.clean(e, 1000)) >= 3
        limit 40) z;
      if jsonb_array_length(v_items) = 0 then
        raise exception 'add at least one question' using errcode = '22023';
      end if;
      v := v || jsonb_build_object('questions', v_items, 'advice', private.clean(p_payload->>'advice', 3000));
    end if;

  elsif p_kind = 'resource' then
    v_subject := nullif(upper(private.clean(p_payload->>'subject', 20)), '');
    if v_subject is not null and not exists (select 1 from public.subjects where code = v_subject) then
      raise exception 'invalid subject' using errcode = '22023';
    end if;
    v := jsonb_build_object(
      'title', private.clean(p_payload->>'title', 120),
      'url', private.clean(p_payload->>'url', 500),
      'subject', v_subject,
      'kind', private.clean(p_payload->>'kind', 20));
    if char_length(v->>'title') < 3 or (v->>'url') !~ '^https://[A-Za-z0-9.-]+\.[A-Za-z]{2,}(/[^[:space:]<>"]*)?$'
       or (v->>'kind') not in ('Guide','Video','Code','Tool','Notes','Other') then
      raise exception 'invalid resource' using errcode = '22023';
    end if;
  else
    raise exception 'invalid submission' using errcode = '22023';
  end if;

  insert into public.submissions (user_id, kind, payload) values (u, p_kind, v) returning id into v_id;
  return v_id;
end $$;

create function public.my_submissions() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
begin
  if auth.uid() is null then raise exception 'sign in required' using errcode = '28000'; end if;
  return coalesce((
    select jsonb_agg(x) from (
      select id, kind, payload, status, note, created_at
