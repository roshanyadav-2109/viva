-- Viva schema. Every table is locked: no direct grants to anon/authenticated.
-- All access goes through the SECURITY DEFINER functions at the bottom.

create extension if not exists pg_trgm with schema extensions;
drop extension if exists pg_graphql;

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create table public.subjects (
  code text primary key,
  name text not null,
  sort smallint not null
);

create table public.proctors (
  id integer generated always as identity primary key,
  code text not null unique check (code ~ '^[A-Za-z0-9][A-Za-z0-9 ._-]{1,39}$'),
  created_at timestamptz not null default now()
);

create table public.sets (
  id bigint generated by default as identity primary key,
  subject text not null references public.subjects(code),
  level smallint not null check (level between 1 and 3),
  proctor_id integer not null references public.proctors(id),
  held_on date,
  created_at timestamptz not null default now()
);

create table public.questions (
  id bigint generated by default as identity primary key,
  set_id bigint references public.sets(id) on delete cascade,
  subject text not null references public.subjects(code),
  level smallint not null check (level between 1 and 3),
  proctor_id integer not null references public.proctors(id),
  position integer,
  body text not null check (char_length(body) between 1 and 2000),
  times_asked integer not null default 1 check (times_asked >= 1),
  asked_on date,
  created_at timestamptz not null default now()
);

create table public.reviews (
  id bigint generated by default as identity primary key,
  set_id bigint references public.sets(id) on delete cascade,
  proctor_id integer not null references public.proctors(id),
  subject text not null references public.subjects(code),
  level smallint not null check (level between 1 and 3),
  body text not null check (char_length(body) between 1 and 3000),
  held_on date,
  created_at timestamptz not null default now()
);

create table public.resources (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 3 and 120),
  url text not null check (char_length(url) <= 500 and url ~ '^https://[A-Za-z0-9.-]+\.[A-Za-z]{2,}(/[^[:space:]<>"]*)?$'),
  subject text references public.subjects(code),
  kind text not null check (kind in ('Guide','Video','Code','Tool','Notes','Other')),
  created_at timestamptz not null default now()
);

create table public.submissions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  kind text not null check (kind in ('session','review','proctor','resource')),
  payload jsonb not null,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  note text,
  created_at timestamptz not null default now(),
  reviewed_at timestamptz
);

create table public.admin_emails (email text primary key check (email = lower(email)));

create table public.usage (
  user_id uuid not null references auth.users(id) on delete cascade,
  hour timestamptz not null,
  calls integer not null default 0,
  rows_read integer not null default 0,
  primary key (user_id, hour)
);

create index questions_body_trgm on public.questions using gin (body extensions.gin_trgm_ops);
create index questions_filter on public.questions (subject, level, proctor_id);
create index questions_asked on public.questions (times_asked desc, id desc);
create index questions_set on public.questions (set_id, position);
create index sets_proctor on public.sets (proctor_id, held_on desc);
create index reviews_proctor on public.reviews (proctor_id, held_on desc);
create index reviews_set on public.reviews (set_id);
create index submissions_status on public.submissions (status, created_at);
create index submissions_user on public.submissions (user_id, created_at desc);

do $$
declare t text;
begin
  foreach t in array array['subjects','proctors','sets','questions','reviews','resources','submissions','admin_emails','usage'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from public, anon, authenticated', t);
  end loop;
end $$;

alter default privileges in schema public revoke all on tables from anon, authenticated;
alter default privileges in schema public revoke all on functions from public, anon, authenticated;

