create or replace function public.admin_remove(p_kind text, p_id bigint) returns void
language plpgsql security definer set search_path = '' as $$
declare k text; s text;
begin
  if not private.is_admin() then raise exception 'not allowed' using errcode = '42501'; end if;
  if p_kind = 'question' then
    select lower(private.qclean(body)), subject into k, s from public.questions where id = p_id;
    delete from public.questions where subject = s and lower(private.qclean(body)) = k;
