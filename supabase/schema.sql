create function public.me() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare u record;
begin
  select id, email, raw_user_meta_data into u from auth.users where id = auth.uid();
  if u.id is null then return null; end if;
  return jsonb_build_object(
    'id', u.id,
    'email', u.email,
    'name', coalesce(u.raw_user_meta_data->>'full_name', u.raw_user_meta_data->>'name', split_part(u.email, '@', 1)),
    'avatar', u.raw_user_meta_data->>'avatar_url',
    'admin', private.is_admin()
  );
end $$;

