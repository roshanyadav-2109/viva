create function public.search_questions(
  p_q text default null, p_subject text default null, p_level integer default null,
  p_proctor text default null, p_sort text default 'asked',
  p_limit integer default 20, p_offset integer default 0
) returns table (
  id bigint, body text, subject text, level smallint, proctor text,
  set_id bigint, times_asked integer, asked_on date, total bigint
)
language plpgsql security definer set search_path = '' as $$
declare
  v_limit integer := least(greatest(coalesce(p_limit, 20), 1), 30);
  v_offset integer := greatest(coalesce(p_offset, 0), 0);
  v_q text := nullif(private.clean(p_q, 100), '');
begin
  if v_offset > 1500 then
    raise exception 'refine your search' using errcode = '22023';
  end if;
  perform private.touch(v_limit);
  return query
  select q.id, q.body, q.subject, q.level, p.code, q.set_id, q.times_asked, q.asked_on, count(*) over ()
  from public.questions q
  join public.proctors p on p.id = q.proctor_id
  where (v_q is null or q.body ilike '%' || private.like_escape(v_q) || '%')
    and (p_subject is null or q.subject = p_subject)
    and (p_level is null or q.level = p_level)
    and (p_proctor is null or lower(p.code) = lower(p_proctor))
  order by
    (case when p_sort = 'asked' then q.times_asked end) desc nulls last,
    (case when p_sort = 'recent' then q.asked_on end) desc nulls last,
    q.id desc
  limit v_limit offset v_offset;
end $$;

create function public.list_proctors(
  p_q text default null, p_subject text default null, p_sort text default 'questions',
  p_limit integer default 24, p_offset integer default 0
) returns table (code text, questions bigint, sets bigint, reviews bigint, total bigint)
language plpgsql security definer set search_path = '' as $$
declare
  v_limit integer := least(greatest(coalesce(p_limit, 24), 1), 30);
  v_offset integer := least(greatest(coalesce(p_offset, 0), 0), 600);
  v_q text := nullif(private.clean(p_q, 40), '');
begin
  perform private.touch(v_limit);
  return query
  with qs as (
    select proctor_id, count(*) n from public.questions
    where p_subject is null or subject = p_subject group by 1),
  ss as (
    select proctor_id, count(*) n from public.sets
    where p_subject is null or subject = p_subject group by 1),
  rv as (
    select proctor_id, count(*) n from public.reviews
    where p_subject is null or subject = p_subject group by 1)
  select p.code, coalesce(qs.n, 0), coalesce(ss.n, 0), coalesce(rv.n, 0), count(*) over ()
  from public.proctors p
  left join qs on qs.proctor_id = p.id
  left join ss on ss.proctor_id = p.id
  left join rv on rv.proctor_id = p.id
  where (v_q is null or p.code ilike '%' || private.like_escape(v_q) || '%')
    and (p_subject is null or ss.n > 0)
  order by
    (case when p_sort = 'questions' then coalesce(qs.n, 0) end) desc nulls last,
    (case when p_sort = 'reviews' then coalesce(rv.n, 0) end) desc nulls last,
    p.code
  limit v_limit offset v_offset;
end $$;

create function public.get_proctor(p_code text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  pid integer;
  pcode text;
begin
  perform private.touch(80);
  select id, code into pid, pcode from public.proctors where lower(code) = lower(private.clean(p_code, 40));
  if pid is null then return null; end if;
  return jsonb_build_object(
    'code', pcode,
    'questions', (select count(*) from public.questions where proctor_id = pid),
    'sets', coalesce((
      select jsonb_agg(x) from (
        select s.id, s.subject, s.level, s.held_on,
               (select count(*) from public.questions q where q.set_id = s.id) as questions
        from public.sets s where s.proctor_id = pid
        order by s.held_on desc nulls last, s.id desc limit 40) x), '[]'::jsonb),
    'reviews', coalesce((
      select jsonb_agg(x) from (
        select r.id, r.body, r.subject, r.level, r.held_on, r.set_id
        from public.reviews r where r.proctor_id = pid
        order by r.held_on desc nulls last, r.id desc limit 40) x), '[]'::jsonb),
    'top', coalesce((
      select jsonb_agg(x) from (
        select q.id, q.body, q.times_asked, q.subject
        from public.questions q where q.proctor_id = pid
        order by q.times_asked desc, q.id desc limit 12) x), '[]'::jsonb)
  );
end $$;

create function public.get_set(p_id bigint) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare s record;
begin
  perform private.touch(130);
  select s0.id, s0.subject, s0.level, s0.held_on, p.code
  into s from public.sets s0 join public.proctors p on p.id = s0.proctor_id where s0.id = p_id;
  if s.id is null then return null; end if;
  return jsonb_build_object(
    'id', s.id, 'subject', s.subject, 'level', s.level, 'held_on', s.held_on, 'proctor', s.code,
    'questions', coalesce((
      select jsonb_agg(x) from (
        select q.id, q.position, q.body, q.times_asked
        from public.questions q where q.set_id = s.id
        order by q.position nulls last, q.id limit 120) x), '[]'::jsonb),
    'reviews', coalesce((
      select jsonb_agg(x) from (
        select r.id, r.body from public.reviews r where r.set_id = s.id order by r.id limit 10) x), '[]'::jsonb)
  );
end $$;

create function public.home_feed() returns jsonb
language plpgsql security definer set search_path = '' as $$
begin
  perform private.touch(24);
  return jsonb_build_object(
    'top', coalesce((
      select jsonb_agg(x) from (
        select min(q.id) as id, min(q.body) as body, min(q.subject) as subject, min(q.level) as level,
               sum(q.times_asked)::int as times_asked, min(p.code) as proctor
        from public.questions q join public.proctors p on p.id = q.proctor_id
        where char_length(q.body) between 20 and 160
        group by lower(q.body)
        order by sum(q.times_asked) desc, min(q.id) desc limit 8) x), '[]'::jsonb),
    'reviews', coalesce((
      select jsonb_agg(x) from (
        select r.id, r.body, r.subject, r.level, r.held_on, p.code as proctor
        from public.reviews r join public.proctors p on p.id = r.proctor_id
        where char_length(r.body) between 40 and 400
        order by r.created_at desc, r.held_on desc nulls last, r.id desc limit 6) x), '[]'::jsonb),
    'resources', coalesce((
      select jsonb_agg(x) from (
        select id, title, url, subject, kind from public.resources order by created_at desc limit 4) x), '[]'::jsonb)
  );
end $$;

