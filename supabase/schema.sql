create or replace function public.toggle_vote(p_id bigint) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  u uuid := auth.uid();
  s text;
  k text;
  n integer;
  mine boolean;
begin
  perform private.touch(0);
  select q.subject, lower(private.qclean(q.body)) into s, k from public.questions q where q.id = p_id;
  if s is null then raise exception 'question not found' using errcode = '22023'; end if;
  if exists (select 1 from public.question_votes where user_id = u and subject = s and qkey = k) then
    delete from public.question_votes where user_id = u and subject = s and qkey = k;
    mine := false;
  else
    insert into public.question_votes (user_id, subject, qkey) values (u, s, k);
    mine := true;
  end if;
  select count(*) into n from public.question_votes where subject = s and qkey = k;
  return jsonb_build_object('votes', n, 'voted', mine);
end $$;

