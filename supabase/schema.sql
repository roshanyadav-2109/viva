declare f record;
begin
  for f in
    select p.oid::regprocedure as sig, p.proname
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.prokind = 'f'
  loop
    execute format('revoke all on function %s from public, anon, authenticated', f.sig);
    if f.proname = 'site_stats' then
      execute format('grant execute on function %s to anon, authenticated', f.sig);
    else
      execute format('grant execute on function %s to authenticated', f.sig);
    end if;
  end loop;
end $$;
create or replace function public.preview_questions() returns table (body text, times_asked integer)
language sql stable security definer set search_path = '' as $$
  select min(q.body), sum(q.times_asked)::int
  from public.questions q
  where q.body ~ '\?$' and char_length(q.body) between 25 and 110
  group by lower(q.body)
  order by sum(q.times_asked) desc, min(q.id)
  limit 2;
$$;
create or replace function private.qclean(p text) returns text
language sql immutable set search_path = '' as $$
  select btrim(regexp_replace(regexp_replace(replace(p, '**', ''), '^[\s\-\*#>•·]+', ''), '^\d{1,2}[\.\)]\s*', ''));
