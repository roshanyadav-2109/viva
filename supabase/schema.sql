create function public.admin_review(p_id bigint, p_approve boolean, p_note text default null) returns void
language plpgsql security definer set search_path = '' as $$
declare
  s public.submissions;
  pid integer;
  sid bigint;
  qn text;
  i integer := 0;
begin
  if not private.is_admin() then raise exception 'not allowed' using errcode = '42501'; end if;
  select * into s from public.submissions where id = p_id for update;
  if s.id is null or s.status <> 'pending' then
    raise exception 'submission not pending' using errcode = '22023';
  end if;

  if p_approve then
    if s.kind = 'proctor' then
      perform private.proctor_id(s.payload->>'code', true);

    elsif s.kind = 'resource' then
      insert into public.resources (title, url, subject, kind)
      values (s.payload->>'title', s.payload->>'url', s.payload->>'subject', s.payload->>'kind');

    elsif s.kind = 'review' then
      pid := private.proctor_id(s.payload->>'proctor', true);
      insert into public.reviews (proctor_id, subject, level, body, held_on)
      values (pid, s.payload->>'subject', (s.payload->>'level')::int, s.payload->>'body', (s.payload->>'held_on')::date);

    elsif s.kind = 'session' then
      pid := private.proctor_id(s.payload->>'proctor', true);
      insert into public.sets (subject, level, proctor_id, held_on)
      values (s.payload->>'subject', (s.payload->>'level')::int, pid, (s.payload->>'held_on')::date)
      returning id into sid;
      for qn in select jsonb_array_elements_text(s.payload->'questions') loop
        i := i + 1;
        insert into public.questions (set_id, subject, level, proctor_id, position, body, asked_on)
        values (sid, s.payload->>'subject', (s.payload->>'level')::int, pid, i, qn, (s.payload->>'held_on')::date);
      end loop;
      if char_length(coalesce(s.payload->>'advice', '')) >= 10 then
        insert into public.reviews (set_id, proctor_id, subject, level, body, held_on)
        values (sid, pid, s.payload->>'subject', (s.payload->>'level')::int, s.payload->>'advice', (s.payload->>'held_on')::date);
      end if;
    end if;
  end if;

  update public.submissions
  set status = case when p_approve then 'approved' else 'rejected' end,
      note = nullif(private.clean(p_note, 300), ''),
      reviewed_at = now()
  where id = s.id;
end $$;

create function public.admin_remove(p_kind text, p_id bigint) returns void
language plpgsql security definer set search_path = '' as $$
begin
  if not private.is_admin() then raise exception 'not allowed' using errcode = '42501'; end if;
  if p_kind = 'question' then delete from public.questions where id = p_id;
  elsif p_kind = 'review' then delete from public.reviews where id = p_id;
  elsif p_kind = 'resource' then delete from public.resources where id = p_id;
  else raise exception 'invalid kind' using errcode = '22023';
  end if;
end $$;

