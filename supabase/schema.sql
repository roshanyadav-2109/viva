create function private.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (
    select 1
    from auth.users u
    join public.admin_emails e on e.email = lower(u.email)
    where u.id = auth.uid() and u.email_confirmed_at is not null
  );
$$;

create function private.touch(p_rows integer) returns void
language plpgsql security definer set search_path = '' as $$
declare
  u uuid := auth.uid();
  r record;
begin
  if u is null then
    raise exception 'sign in required' using errcode = '28000';
  end if;
  insert into public.usage as x (user_id, hour, calls, rows_read)
  values (u, date_trunc('hour', now()), 1, greatest(p_rows, 0))
  on conflict (user_id, hour)
  do update set calls = x.calls + 1, rows_read = x.rows_read + excluded.rows_read
  returning x.calls, x.rows_read into r;
  if r.calls > 900 or r.rows_read > 3000 then
    raise exception 'too many requests, try again later' using errcode = '54000';
  end if;
end $$;

create function private.clean(p text, p_max integer) returns text
language sql immutable set search_path = '' as $$
  select left(btrim(regexp_replace(coalesce(p, ''), '[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]', '', 'g')), p_max);
$$;

create function private.like_escape(p text) returns text
language sql immutable set search_path = '' as $$
  select replace(replace(replace(p, '\', '\\'), '%', '\%'), '_', '\_');
$$;

create function private.proctor_id(p_code text, p_create boolean) returns integer
language plpgsql security definer set search_path = '' as $$
declare v integer;
begin
  select id into v from public.proctors where lower(code) = lower(p_code);
  if v is null and p_create then
    insert into public.proctors (code) values (p_code) returning id into v;
  end if;
  return v;
end $$;

